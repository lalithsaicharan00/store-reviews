ROOTS = {"A": "App Store Reviews", "P": "Play Store Reviews", "N": "Native Store Reviews"}
def _norm(s):
    s = html.unescape(s).replace("\u2019", "'").replace("\u2018", "'").replace("\u201c", '"').replace("\u201d", '"')
    return re.sub(r"\s+", " ", s).strip().lower()
def _review(cite, cache={}):
    p, rest = cite[0], cite[1:]; n, i = rest.split("#")
    key = (p, n)
    if key not in cache:
        folder = next(d for d in os.listdir(ROOTS[p]) if d.split(".")[0] == n)
        with open(os.path.join(ROOTS[p], folder, "reviews.jsonl"), encoding="utf-8") as f: cache[key] = f.readlines()
    r = json.loads(cache[key][int(i)])
    return " ".join(x for x in (r.get("title"), r.get("body"), r.get("text")) if x)
def check():
    assert all(c in CODEBOOK for v in CODES.values() for c in v), "unknown code"
    for cite in CODES: _review(cite)
    missing = [(c, q) for c, q in QUOTES if _norm(q) not in _norm(_review(c))]
    print(len(CODES), "coded reviews;", len(QUOTES), "quotes;", len(missing), "quotes not found", missing)
if __name__ == "__main__": check()
