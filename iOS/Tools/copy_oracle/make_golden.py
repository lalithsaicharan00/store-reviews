"""Writes iOS/Habits/Model/CopyCheckCases.swift: every case reviewed in copy_oracle.py, with the oracle's output,
for CopyCheck to compare against HabitCopy on the phone. Run from this folder: python3 make_golden.py"""
import itertools, json
from copy_oracle import *
from habits_cases import HABITS

OUT = "../../Habits/Model/CopyCheckCases.swift"


def q(s): return json.dumps(s, ensure_ascii=False)
def setlit(xs): return "[" + ", ".join(str(x) for x in sorted(xs)) + "]"


def cal_lit(r):
    parts = [f"unit: .{r['unit']}", f"interval: {r.get('interval', 1)}"]
    if "weekdays" in r: parts.append(f"weekdays: {setlit(r['weekdays'])}")
    if "dates" in r: parts.append(f"dates: {setlit(r['dates'])}")
    if "pattern" in r: parts.append(f"pattern: .{r['pattern']}")
    if "ordinal" in r: parts.append(f"ordinal: {r['ordinal']}")
    if "weekday" in r: parts.append(f"weekday: {r['weekday']}")
    if "month" in r: parts.append(f"month: {r['month']}")
    if "day" in r: parts.append(f"day: {r['day']}")
    if "useLastDay" in r: parts.append(f"useLastDay: {'true' if r['useLastDay'] else 'false'}")
    return "CalendarSchedule(" + ", ".join(parts) + ")"


def freq_lit(f):
    k = f[0]
    if k == "daily": return ".daily"
    if k == "weekdays": return f".weekdays({setlit(f[1])})"
    if k in ("perWeek", "perMonth", "perYear"): return f".{k}({f[1]})"
    if k == "flexible": return f".flexible(.{f[1]}, {f[2]})"
    if k == "calendar": return f".calendar({cal_lit(f[1])})"
    raise ValueError(k)


def kind_lit(h):
    if h["kind"] == "amount": return f".amount(unit: {q(h['unit'])}, increment: 1)"
    return "." + h["kind"]


lines = ["#if DEBUG",
         "// Generated by iOS/Tools/copy_oracle/make_golden.py from copy_oracle.py. Do not edit by hand:",
         "// change the oracle, review its print-out, and generate again.",
         "",
         "enum CopyCheckCases {",
         "    /// (days, week start, full phrase, short phrase): all 127 day sets, weeks starting Monday and Sunday.",
         "    static let weekdays: [(Set<Int>, Int, String, String)] = ["]
for ws in (2, 1):
    for r in range(1, 8):
        for combo in itertools.combinations(range(1, 8), r):
            lines.append(f"        ({setlit(combo)}, {ws}, {q(days_text(set(combo), ws))}, {q(days_text(set(combo), ws, short=True))}),")
lines.append("    ]")

DATES = [[1], [15], [1, 15], [1, 10, 20], [31], [30], [29, 30, 31], [1, 2, 3, 4, 5], [1, 2, 3, 15], [1, 2, 3, 10, 11, 12], [1, 2],
         [5, 6, 20, 21], [1, 5, 9, 13, 17, 21, 25], list(range(1, 32, 2)), list(range(2, 31, 2)), list(range(1, 32)), list(range(1, 31)),
         [1, 15, 28, 31], [28, 29, 30, 31], [1, 2, 4, 5, 7, 8], [2, 3], list(range(1, 29)), [1, 3, 5, 7, 9, 11], [7, 14, 21, 28]]
lines.append("    /// (dates, use the last day, every N months, phrase).")
lines.append("    static let dates: [(Set<Int>, Bool, Int, String)] = [")
for d in DATES:
    for last in (True, False):
        for n in (1, 2, 3):
            lines.append(f"        ({setlit(d)}, {'true' if last else 'false'}, {n}, {q(month_dates_text(set(d), last, n))}),")
lines.append("    ]")

RULES = []
for n in (1, 2, 3, 14): RULES.append(dict(unit="day", interval=n))
for n in (1, 2, 3):
    for days in ({2}, {2, 4}, {1, 2, 3, 4, 5}, {2, 3, 4, 5, 6}, {1, 7}, set(range(1, 8)), {2, 3, 4, 5, 6, 7}, {3, 5, 7}):
        RULES.append(dict(unit="week", interval=n, weekdays=days))
for n in (1, 2, 6):
    RULES.append(dict(unit="month", interval=n, pattern="last"))
    for o in (1, 2, 3, 4, 5, -1):
        RULES.append(dict(unit="month", interval=n, pattern="weekday", ordinal=o, weekday=7))
for m, d, n in ((10, 1, 1), (2, 29, 1), (12, 25, 2), (1, 1, 5), (7, 31, 1)):
    RULES.append(dict(unit="year", interval=n, month=m, day=d))
lines.append("    /// (rule, week start, full phrase, short phrase).")
lines.append("    static let calendars: [(CalendarSchedule, Int, String, String)] = [")
for r in RULES:
    for ws in (2, 1):
        lines.append(f"        ({cal_lit(r)}, {ws}, {q(calendar_text(r, ws))}, {q(calendar_text(r, ws, short=True))}),")
lines.append("    ]")

lines.append("    /// (habit, week start, sentence, Today's caption).")
lines.append("    static let habits: [(Habit, Int, String, String)] = [")
for h in HABITS:
    for ws in (2, 1):
        cu = f", checkUnit: {q(h['checkUnit'])}" if h.get("checkUnit") else ""
        am = ", atMost: true" if h.get("atMost") else ""
        g = h["goal"]
        habit = f"Habit(name: {q(h['name'])}, symbol: \"star\", color: .blue, kind: {kind_lit(h)}, goal: {g}, frequency: {freq_lit(h['frequency'])}{cu}{am})"
        lines.append(f"        ({habit}, {ws}, {q(sentence(h, ws))}, {q(caption(h, ws))}),")
lines.append("    ]")

UNITS = [(1, "glasses"), (2, "glasses"), (1, "cups"), (1, "pages"), (1, "steps"), (1, "push-ups"), (1, "Push-ups"), (1, "km"), (1, "ml"),
         (1, "litres"), (1, "miles"), (1, "boxes"), (1, "dishes"), (1, "berries"), (1, "series"), (1, "glass"), (1, "prayers"),
         (1, "coffees"), (1, "lbs"), (1, "class"), (1, "bus"), (1, "times"), (1, "hours"), (1, "minutes"), (1, "$"), (0.5, "glasses")]
lines.append("    /// (value, unit, the unit's word).")
lines.append("    static let units: [(Double, String, String)] = [")
for v, u in UNITS: lines.append(f"        ({v}, {q(u)}, {q(unit_word(v, u))}),")
lines.append("    ]")
AMOUNTS = [(8, "glasses"), (1, "glasses"), (2000, "ml"), (2.5, "litres"), (10000, "steps"), (0.25, "l"), (100, "$"), (1234.5, "km"),
           (8, ""), (1, "chapters"), (12, "books"), (1000000, "steps")]
lines.append("    /// (value, unit, amount text).")
lines.append("    static let amounts: [(Double, String, String)] = [")
for v, u in AMOUNTS: lines.append(f"        ({v}, {q(u)}, {q(amount_text(v, u))}),")
lines.append("    ]")
lines.append("}")
lines.append("#endif")
open(OUT, "w").write("\n".join(lines) + "\n")
print("wrote", OUT, len(lines), "lines")
